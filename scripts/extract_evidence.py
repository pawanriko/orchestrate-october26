"""Regenerate and audit the checked-in evidence extractions.

PDF evidence is re-extracted deterministically with `pdftotext -layout`
(poppler). PNG screenshots cannot be re-extracted without an OCR engine
(none is installed on this machine), so their transcriptions are curated
visual reads checked in under evidence/extracted/ and only *verified* here.

Layout of evidence/extracted/ (all paths relative to the repo root):

    <file_id>.txt       human-readable transcription of the source file.
                        For PDFs this file is regenerated by this script
                        (do not hand-edit the body: it will be overwritten).
                        For PNGs this file is the curated transcription.
    <file_id>.records   machine-readable RECORD lines consumed by the
                        engine (see src/engine.py parse_extracted_records).
                        A source file with no attributable resource gets
                        NO .records file; a "NO RECORDS:" note explaining
                        why must then exist, either in its .txt (PNGs) or
                        in a curated <file_id>.notes file that this script
                        appends to regenerated PDF text, so a gap is never
                        a silent skip.
    <file_id>.notes     optional curated appendix for regenerated PDF text
                        (e.g. the NO RECORDS note). Never overwritten.

Usage:
    python3 scripts/extract_evidence.py --dataset <dataset_dir>
    python3 scripts/extract_evidence.py --dataset <dataset_dir> --check-only
"""

import argparse
import csv
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXTRACTED = ROOT / "evidence" / "extracted"

HEADER = """# source: {rel}
# file_id: {file_id}
# captured_at: {captured_at}
# method: {method}
# NOTE: transcription below is for human audit. The engine reads only
# the sibling <file_id>.records file (RECORD lines), never this text.
"""


def fail(message: str) -> int:
    print(f"extract_evidence: ERROR: {message}", file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", required=True, help="dataset/ directory")
    parser.add_argument("--check-only", action="store_true",
                        help="verify only, do not regenerate PDF text")
    args = parser.parse_args()

    dataset = Path(args.dataset)
    manifest_path = dataset / "evidence_files.csv"
    if not manifest_path.exists():
        return fail(f"no manifest at {manifest_path}")
    with open(manifest_path, newline="", encoding="utf-8") as handle:
        manifest = list(csv.DictReader(handle))

    if not args.check_only:
        pdftotext = shutil.which("pdftotext")
        if pdftotext is None:
            return fail("pdftotext not found; cannot regenerate PDF text")
        EXTRACTED.mkdir(parents=True, exist_ok=True)
        for row in manifest:
            path = dataset / row["file_path"]
            if path.suffix.lower() != ".pdf":
                continue
            out = EXTRACTED / f"{row['file_id']}.txt"
            body = subprocess.run(
                [pdftotext, "-layout", str(path), "-"],
                capture_output=True, text=True, check=True).stdout
            text = (
                HEADER.format(
                    rel=row["file_path"], file_id=row["file_id"],
                    captured_at=row["captured_at"],
                    method="pdftotext -layout (poppler), deterministic")
                + "\n" + body)
            notes = EXTRACTED / f"{row['file_id']}.notes"
            if notes.exists():
                text += "\n" + notes.read_text(encoding="utf-8")
            out.write_text(text, encoding="utf-8")
            print(f"regenerated {out.name} from {row['file_path']}")

    # Audit: every PDF/PNG in the manifest must have a transcription, and
    # either a .records file or an explicit NO RECORDS note in the .txt.
    problems = []
    for row in manifest:
        path = dataset / row["file_path"]
        if path.suffix.lower() not in (".pdf", ".png"):
            continue
        txt = EXTRACTED / f"{row['file_id']}.txt"
        rec = EXTRACTED / f"{row['file_id']}.records"
        if not txt.exists():
            problems.append(f"{row['file_id']}: missing {txt.name}")
            continue
        if not rec.exists() and "NO RECORDS:" not in txt.read_text(
                encoding="utf-8", errors="ignore"):
            problems.append(
                f"{row['file_id']}: no .records file and no NO RECORDS note")
    if problems:
        for problem in problems:
            print(f"extract_evidence: ERROR: {problem}", file=sys.stderr)
        return 1
    print("extract_evidence: audit OK "
          f"({sum(1 for r in manifest if Path(dataset / r['file_path']).suffix.lower() in ('.pdf', '.png'))} pdf/png sources)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
